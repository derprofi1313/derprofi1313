import { readFile } from "node:fs/promises";
import path from "node:path";

const generatedAssets = [
  "profile-stats.svg",
  "profile-stats-mobile.svg",
  "contribution-signal.svg",
  "contribution-signal-mobile.svg",
];

function fail(message) {
  throw new Error(`Profile output validation failed: ${message}`);
}

function extractGeneratedDate(value, label) {
  const match = value.match(/Generated (\d{4}-\d{2}-\d{2}) from public GitHub data/);

  if (!match) {
    fail(`${label} is missing the generated-date marker`);
  }

  return match[1];
}

const readmePath = path.join(process.cwd(), "README.md");
const assetsDirectory = path.join(process.cwd(), "assets");
const readme = await readFile(readmePath, "utf8");
const snapshotMatch = readme.match(
  /<!-- profile-data:start -->\s+\*\*Current public snapshot:\*\* ([\s\S]*?)\s+<!-- profile-data:end -->/,
);

if (!snapshotMatch) {
  fail("README snapshot block is missing or malformed");
}

const readmeDate = extractGeneratedDate(snapshotMatch[1], "README snapshot");
const statsMatch = snapshotMatch[1].match(
  /([0-9,]+) owned non-fork repositor(?:y|ies) · ([0-9,]+) stars? · ([0-9,]+) contributions? in the rolling 12 months/,
);
const contributionMatch = snapshotMatch[1].match(
  /([0-9,]+) contributions? in the rolling 12 months/,
);

if (!statsMatch) {
  fail("README snapshot is missing the repository, star, or contribution totals");
}

if (!contributionMatch) {
  fail("README snapshot is missing the contribution total");
}

const [, repositoryCount, starCount, contributionCount] = statsMatch.map((value) =>
  value.replaceAll(",", ""),
);
const expectedStatsDescription =
  `${repositoryCount} public source repositories, ${starCount} stars, and ` +
  `${contributionCount} contributions across the last 12 months.`;

for (const asset of generatedAssets) {
  const svg = await readFile(path.join(assetsDirectory, asset), "utf8");

  if (!/^<\?xml version="1\.0" encoding="UTF-8"\?>\r?\n<svg/.test(svg)) {
    fail(`${asset} is not an SVG document generated by the renderer`);
  }

  if (/<script\b/i.test(svg)) {
    fail(`${asset} contains a script tag`);
  }

  const assetDate = extractGeneratedDate(svg, asset);

  if (assetDate !== readmeDate) {
    fail(`${asset} generated date ${assetDate} does not match README ${readmeDate}`);
  }

  if (
    asset.startsWith("profile-stats") &&
    !svg.includes(expectedStatsDescription)
  ) {
    fail(`${asset} metrics do not match the README snapshot`);
  }
}

const contributionSvg = await readFile(
  path.join(assetsDirectory, "contribution-signal.svg"),
  "utf8",
);

if (!contributionSvg.includes(`${contributionMatch[1]} contributions across the last 12 months`)) {
  fail("contribution SVG total does not match the README snapshot");
}

console.log(`Profile output validation passed for ${readmeDate}.`);
